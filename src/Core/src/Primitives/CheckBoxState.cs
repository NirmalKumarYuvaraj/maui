namespace Microsoft.Maui;

/// <summary>
/// Specifies the state of a checkbox.
/// </summary>
public enum CheckBoxState
{
	/// <summary>The checkbox is not checked.</summary>
	Unchecked = 0,

	/// <summary>The checkbox is checked.</summary>
	Checked,

	/// <summary>The checkbox is neither checked nor unchecked (mixed).</summary>
	Indeterminate
}
